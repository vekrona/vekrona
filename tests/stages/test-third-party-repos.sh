#!/usr/bin/env bash
# Third-party repos reach root unpinned unless their repo file pins the key and lists the packages vekrona takes from them.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
source "$ROOT/tests/lib.sh"
source "$ROOT/lib/cuda-repo.sh"
REPOS="$ROOT/etc/yum.repos.d"
KEYS="$ROOT/etc/pki/rpm-gpg"

# repo_setting FILE KEY: the value of the one KEY= line of the repo file.
repo_setting() {
  local lines
  lines="$(file_grep "^$2=" "$1")"
  [[ "$(wc -l <<<"$lines")" -eq 1 && -n "$lines" ]] || die "$1 must hold exactly one $2= line, found: ${lines:-none}"
  printf '%s' "${lines#*=}"
}

for copr in "${VEKRONA_COPRS[@]}"; do
  key_repo="$(copr_key_repo "$copr")"
  file="$REPOS/$key_repo.repo"
  [[ -f "$file" ]] || die "no repo file for the COPR $copr: $file"
  [[ "$(sed -n '1p' "$file")" == "[$(copr_id "$copr")]" ]] || die "$file does not declare the repo id $(copr_id "$copr"), which VEKRONA_PINNED_PKGS and dnf's from_repo use"
  [[ "$(repo_setting "$file" gpgkey)" == "file://$VEKRONA_REPO_KEY_DIR/$(repo_key_name "$key_repo")" ]] || die "$file takes its key from somewhere but the pinned key file"
  [[ "$(repo_setting "$file" gpgcheck)" == 1 ]] || die "$file does not check package signatures"
  [[ -n "$(repo_setting "$file" includepkgs)" ]] || die "$file offers every package of the COPR"
  assert_repo_key_file_pinned "$key_repo" "$KEYS/$(repo_key_name "$key_repo")"
done
log "ok: every COPR has a repo file with its own id, a pinned vendored key and a package list"

for pkg in "${!VEKRONA_PINNED_PKGS[@]}"; do
  repo_id="${VEKRONA_PINNED_PKGS[$pkg]}"
  for copr in "${VEKRONA_COPRS[@]}"; do
    [[ "$(copr_id "$copr")" == "$repo_id" ]] || continue
    read -ra allowed <<<"$(repo_setting "$REPOS/$(copr_key_repo "$copr").repo" includepkgs)"
    printf '%s\n' "${allowed[@]}" | grep -qxF "$pkg" || die "$pkg is pinned to $repo_id, whose includepkgs lacks it: ${allowed[*]}"
  done
done
log "ok: a package pinned to a COPR is on that COPR's list"

for pkg in xremap-wlroots ghostty; do
  found=0
  for copr in "${VEKRONA_COPRS[@]}"; do
    read -ra allowed <<<"$(repo_setting "$REPOS/$(copr_key_repo "$copr").repo" includepkgs)"
    printf '%s\n' "${allowed[@]}" | grep -qxF "$pkg" && found=1
  done
  [[ $found -eq 1 ]] || die "no COPR offers $pkg, which the desktop installs from one"
done
log "ok: the packages the desktop takes from COPRs are on a list"

cuda_file="$REPOS/$CUDA_REPO_FILE_NAME"
[[ "$(sed -n '/^\[/p' "$cuda_file")" == "[$CUDA_REPO_ID]" ]] || die "$cuda_file does not declare $CUDA_REPO_ID"
[[ "$(repo_setting "$cuda_file" gpgkey)" == "file://$VEKRONA_REPO_KEY_DIR/$(repo_key_name "$CUDA_KEY_REPO")" ]] || die "the CUDA repo takes its key from somewhere but the pinned key file"
assert_repo_key_file_pinned "$CUDA_KEY_REPO" "$KEYS/$(repo_key_name "$CUDA_KEY_REPO")"
! grep -q '^excludepkgs=' "$cuda_file" || die "the CUDA repo is restricted by a denylist again: a new driver package name would get through"
read -ra cuda_allowed <<<"$(repo_setting "$cuda_file" includepkgs)"

in_cuda_list() {
  local name="$1" pattern
  for pattern in "${cuda_allowed[@]}"; do
    # shellcheck disable=SC2053 # the pattern is a glob on purpose
    [[ "$name" == $pattern ]] && return 0
  done
  return 1
}
for toolkit in cuda-toolkit-13-4 cuda-toolkit-13 cuda-nvcc-13-4 cuda-compiler-13-4 libcublas-13-4 libcufft-devel-13-4 libnpp-13-4 \
  libnvjitlink-13-4 cccl-13-4 nsight-compute-2026.3.1 nsight-systems-2026.3.2 cuda-13-4 cuda; do
  in_cuda_list "$toolkit" || die "the CUDA list does not admit the toolkit package $toolkit"
done
for driver in nvidia-driver nvidia-driver-cuda-libs nvidia-open cuda-drivers cuda-drivers-580 nvidia-kmod-common kmod-nvidia-latest-dkms \
  nvidia-settings nvidia-persistenced nvidia-modprobe libnvidia-fbc xorg-x11-nvidia nvidia-fabricmanager libnvidia-nscq nvidia-gds-13-4 nvidia-imex; do
  ! in_cuda_list "$driver" || die "the CUDA list admits the driver package $driver"
done
log "ok: the CUDA repo admits the toolkit and none of the driver packages the denylist used to name"

# The dnf override file `dnf config-manager setopt` writes: an option is found only in its own repo's section.
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
REPO_OVERRIDE_FILE="$work/99-config_manager.repo"
printf '# Generated by libdnf5.\n[other-repo]\nexcludepkgs=a\n[%s]\nenabled=1\n' "$CUDA_REPO_ID" >"$REPO_OVERRIDE_FILE"
! repo_override_has "$CUDA_REPO_ID" excludepkgs || die "another repo's excludepkgs was taken for the CUDA repo's"
repo_override_has other-repo excludepkgs || die "an excludepkgs override was not found in its section"
rm "$REPO_OVERRIDE_FILE"
! repo_override_has "$CUDA_REPO_ID" excludepkgs || die "a missing override file reads as an override"
log "ok: repo_override_has looks at the section of the repo it was asked about"
